import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createGovernanceRouter } from './governance';

test('authentication protects private routes and completes signup, verification, login, reset, and logout', async t => {
  const previousNodeEnv = process.env.NODE_ENV;
  const previousVerification = process.env.AUTH_EMAIL_VERIFICATION_REQUIRED;
  const previousExpose = process.env.AUTH_DEV_EXPOSE_TOKENS;
  const previousBypass = process.env.CLICKO_DEV_AUTH_BYPASS;
  const previousBypassProfile = process.env.CLICKO_DEV_AUTH_BYPASS_PROFILE;
  process.env.NODE_ENV = 'development';
  process.env.AUTH_EMAIL_VERIFICATION_REQUIRED = 'true';
  process.env.AUTH_DEV_EXPOSE_TOKENS = 'true';
  process.env.CLICKO_DEV_AUTH_BYPASS = 'false';
  const parent = path.resolve(tmpdir());
  const folder = mkdtempSync(path.join(parent, 'clicko-auth-test-'));
  const filename = path.join(folder, 'governance.json');
  const app = express(); app.use(express.json()); app.use('/api/governance', createGovernanceRouter({ dataFile: filename }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  t.after(async () => {
    await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
    if (path.dirname(folder) === parent && path.basename(folder).startsWith('clicko-auth-test-')) rmSync(folder, { recursive: true, force: true });
    process.env.NODE_ENV = previousNodeEnv; process.env.AUTH_EMAIL_VERIFICATION_REQUIRED = previousVerification; process.env.AUTH_DEV_EXPOSE_TOKENS = previousExpose;
    process.env.CLICKO_DEV_AUTH_BYPASS = previousBypass; process.env.CLICKO_DEV_AUTH_BYPASS_PROFILE = previousBypassProfile;
  });
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}/api/governance`;
  const json = (url: string, method = 'GET', body?: unknown, cookie?: string, origin?: string) => fetch(base + url, { method, headers: { 'Content-Type': 'application/json', ...(cookie ? { cookie } : {}), ...(origin ? { origin } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const credentials = { name: 'Conta Segura', email: 'segura@example.test', password: 'SenhaForte9', confirmation: 'SenhaForte9', termsAccepted: true, privacyAccepted: true, remember: true };

  assert.equal((await json('/session')).status, 401);
  assert.equal((await json('/auth/login', 'POST', { email: '', password: '' })).status, 400);
  assert.equal((await json('/auth/login', 'POST', { email: 'invalido', password: 'SenhaForte9' })).status, 400);
  const blankPassword = await json('/auth/login', 'POST', { email: 'nao-cadastrado@example.test', password: '   ' });
  assert.equal(blankPassword.status, 400);
  assert.equal((await blankPassword.json()).error, 'E-mail ou senha incorretos.');
  assert.equal((await json('/auth/login', 'POST', { email: 'nao-cadastrado@example.test', password: 'CredencialInexistente9' })).status, 401);
  process.env.CLICKO_DEV_AUTH_BYPASS = 'true';
  process.env.CLICKO_DEV_AUTH_BYPASS_PROFILE = 'company';
  const bypassPayload = await (await json('/auth/session')).json();
  assert.equal(bypassPayload.account.type, 'company');
  assert.deepEqual(bypassPayload.accounts.map((account: { type: string }) => account.type).sort(), ['company', 'personal']);
  assert.equal(bypassPayload.user.role, 'master');
  assert.equal((await json('/session')).status, 200);
  const personalWorkspaceId = bypassPayload.accounts.find((account: { type: string }) => account.type === 'personal').workspaceId;
  const switchedBypass = await json('/auth/session/workspace', 'POST', { workspaceId: personalWorkspaceId });
  assert.equal(switchedBypass.status, 200);
  const bypassProfileCookie = switchedBypass.headers.get('set-cookie')!.split(';')[0];
  assert.match(switchedBypass.headers.get('set-cookie')!, /HttpOnly/i);
  assert.equal((await (await json('/auth/session', 'GET', undefined, bypassProfileCookie)).json()).account.type, 'personal');
  process.env.NODE_ENV = 'production';
  assert.equal((await json('/auth/session', 'GET', undefined, bypassProfileCookie)).status, 401);
  process.env.NODE_ENV = 'development';
  process.env.CLICKO_DEV_AUTH_BYPASS = 'false';
  assert.equal((await fetch(base + '/session', { headers: { 'x-workspace-id': 'ws-1', 'x-user-id': 'usr-master' } })).status, 401);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, password: 'weak' })).status, 400);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, termsAccepted: false })).status, 400);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, privacyAccepted: false })).status, 400);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, confirmation: 'SenhaDiferente9' })).status, 400);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, name: 'Pedro' })).status, 400);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, name: '123 Silva' })).status, 400);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, email: 'email@invalido' })).status, 400);
  assert.equal((await json('/auth/signup', 'POST', { ...credentials, email: 'pedro.henrique@gmail.com' })).status, 409);
  assert.equal((await json('/auth/signup', 'POST', credentials, undefined, 'https://attacker.invalid')).status, 403);

  const signup = await json('/auth/signup', 'POST', credentials);
  assert.equal(signup.status, 201);
  const signupBody = await signup.json();
  assert.equal(signupBody.verificationRequired, true);
  assert.ok(signupBody.developmentToken);
  assert.equal(signup.headers.get('set-cookie'), null);
  assert.equal((await json('/auth/login', 'POST', { email: credentials.email, password: credentials.password })).status, 403);

  const verified = await json('/auth/verify-email', 'POST', { token: signupBody.developmentToken });
  assert.equal(verified.status, 200);
  const cookie = verified.headers.get('set-cookie')!.split(';')[0];
  assert.match(verified.headers.get('set-cookie')!, /HttpOnly/i);
  assert.match(verified.headers.get('set-cookie')!, /SameSite=Strict/i);
  assert.equal((await json('/auth/verify-email', 'POST', { token: signupBody.developmentToken })).status, 400);
  assert.equal((await json('/session', 'GET', undefined, cookie)).status, 200);
  const secondWorkspace = await json('/workspaces/register', 'POST', { workspaceId: 'ws-auth-company', userId: 'usr-auth-company', name: 'Empresa Segura', type: 'company' }, cookie);
  assert.equal(secondWorkspace.status, 201);
  const switchedSession = await (await json('/auth/session', 'GET', undefined, cookie)).json();
  assert.equal(switchedSession.account.workspaceId, 'ws-auth-company');
  assert.equal(switchedSession.accounts.length, 2);
  const switchedBack = await json('/auth/session/workspace', 'POST', { workspaceId: switchedSession.accounts.find((item: { workspaceId: string }) => item.workspaceId !== 'ws-auth-company').workspaceId }, cookie);
  assert.equal(switchedBack.status, 200);
  assert.equal((await json('/auth/session/workspace', 'POST', { workspaceId: 'ws-foreign' }, cookie)).status, 403);

  const raw = readFileSync(filename, 'utf8');
  assert.equal(raw.includes(credentials.password), false);
  assert.equal(raw.includes(signupBody.developmentToken), false);
  assert.match(raw, /scrypt\$/);
  const persisted = JSON.parse(raw);
  const persistedCredential = persisted.authCredentials.find((item: { email: string }) => item.email === credentials.email);
  assert.equal(persistedCredential.legalConsent.termsVersion, '1.0.0');
  assert.equal(persistedCredential.legalConsent.privacyVersion, '1.0.0');
  assert.ok(Date.parse(persistedCredential.legalConsent.termsAcceptedAt));

  const knownRecovery = await (await json('/auth/forgot-password', 'POST', { email: credentials.email })).json();
  const unknownRecovery = await (await json('/auth/forgot-password', 'POST', { email: 'unknown@example.test' })).json();
  assert.equal(knownRecovery.message, unknownRecovery.message);
  assert.ok(knownRecovery.developmentToken);
  assert.equal(unknownRecovery.developmentToken, undefined);
  assert.equal((await json('/auth/reset-password', 'POST', { token: knownRecovery.developmentToken, password: 'short' })).status, 400);
  const reset = await json('/auth/reset-password', 'POST', { token: knownRecovery.developmentToken, password: 'NovaSenha8' });
  assert.equal(reset.status, 200);
  const resetCookie = reset.headers.get('set-cookie')!.split(';')[0];
  assert.equal((await json('/session', 'GET', undefined, cookie)).status, 401);
  assert.equal((await json('/auth/reset-password', 'POST', { token: knownRecovery.developmentToken, password: 'OutraSenha8' })).status, 400);
  assert.equal((await json('/auth/login', 'POST', { email: credentials.email, password: credentials.password })).status, 401);
  assert.equal((await json('/auth/login', 'POST', { email: credentials.email, password: 'NovaSenha8' })).status, 200);

  const logout = await json('/auth/logout', 'POST', undefined, resetCookie);
  assert.equal(logout.status, 204);
  assert.match(logout.headers.get('set-cookie')!, /Max-Age=0/);
  assert.equal((await json('/session', 'GET', undefined, resetCookie)).status, 401);

  const legacyRecovery = await (await json('/auth/forgot-password', 'POST', { email: 'pedro.henrique@gmail.com' })).json();
  assert.ok(legacyRecovery.developmentToken);
  const claimed = await json('/auth/reset-password', 'POST', { token: legacyRecovery.developmentToken, password: 'PerfilLegado8' });
  assert.equal(claimed.status, 200);
  const claimedPayload = await claimed.json();
  assert.equal(claimedPayload.account.workspaceId, 'ws-personal');
  const claimedCookie = claimed.headers.get('set-cookie')!.split(';')[0];
  process.env.CLICKO_DEV_AUTH_BYPASS = 'true';
  const preview = await (await json('/auth/session', 'GET', undefined, claimedCookie)).json();
  assert.deepEqual(preview.accounts.map((account: { type: string }) => account.type).sort(), ['company', 'personal']);
  const company = preview.accounts.find((account: { type: string }) => account.type === 'company');
  const switched = await json('/auth/session/workspace', 'POST', { workspaceId: company.workspaceId }, claimedCookie);
  assert.equal(switched.status, 200);
  assert.equal((await switched.json()).account.type, 'company');
  process.env.NODE_ENV = 'production';
  const production = await (await json('/auth/session', 'GET', undefined, claimedCookie)).json();
  assert.equal(production.account.workspaceId, 'ws-personal');
  assert.equal((await json('/auth/session/workspace', 'POST', { workspaceId: company.workspaceId }, claimedCookie)).status, 403);
  process.env.NODE_ENV = 'development';
  process.env.CLICKO_DEV_AUTH_BYPASS = 'false';
  assert.equal((await (await json('/auth/session', 'GET', undefined, claimedCookie)).json()).account.workspaceId, 'ws-personal');
});
