export function experienceActionForId(actionId?: string) {
  if (!actionId) return undefined;
  return EXPERIENCE_ACTIONS.find((action) => action.actionId === actionId);
}

export function experienceScreenForLocation(location: string): ExperienceScreen | undefined {
  const route = routeForPath(location);
  if (!route) return undefined;
  return EXPERIENCE_SCREENS
    .filter((screen) => locationMatchesScreenTemplate(location, screen.routeTemplate))
    .sort(
      (left, right) =>
        (right.routeTemplate.split("?")[1]?.length ?? 0) -
        (left.routeTemplate.split("?")[1]?.length ?? 0),
    )[0];
}

function locationMatchesScreenTemplate(
  location: string,
  routeTemplate: string,
): boolean {
  const [locationPath, locationQuery = ""] = location.split("?");
  const [templatePath, templateQuery = ""] = routeTemplate.split("?");
  const escaped = templatePath
    .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    .replace(/:[A-Za-z][A-Za-z0-9_]*/g, "[^/]+");
  if (!new RegExp(`^${escaped}$`).test(locationPath)) return false;
  const required = new URLSearchParams(templateQuery);
  const actual = new URLSearchParams(locationQuery);
  for (const [key, value] of required) {
    const candidate = actual.get(key);
    if (value.startsWith(":")) {
      if (!candidate) return false;
    } else if (candidate !== value) return false;
  }
  return true;
}

export function validateExperienceRegistry(): string[] {
  const issues: string[] = [];
  const actions = new Map(EXPERIENCE_ACTIONS.map((action) => [action.actionId, action]));
  const screens = new Map(EXPERIENCE_SCREENS.map((screen) => [screen.screenId, screen]));
  if (actions.size !== EXPERIENCE_ACTIONS.length) issues.push("duplicate actionId");
  if (screens.size !== EXPERIENCE_SCREENS.length) issues.push("duplicate screenId");

  for (const action of EXPERIENCE_ACTIONS) {
    for (const issue of validateActionContract(action)) {
      issues.push(`${action.actionId}.${issue.field}: ${issue.message}`);
    }
  }
  for (const screen of EXPERIENCE_SCREENS) {
    for (const issue of validateScreenContract(screen, actions)) {
      issues.push(`${screen.screenId}.${issue.field}: ${issue.message}`);
    }
    const route = routeForPath(screen.examplePath);
    if (!route) issues.push(`${screen.screenId}: examplePath has no route owner`);
    else if (route.owner !== screen.owner) {
      issues.push(`${screen.screenId}: expected owner ${screen.owner}, found ${route.owner}`);
    }
  }

  const reachable = new Set(["SCREEN-HOME"]);
  let changed = true;
  while (changed) {
    changed = false;
    for (const { from, to } of EXPERIENCE_FLOW_EDGES) {
      if (reachable.has(from) && !reachable.has(to)) {
        reachable.add(to);
        changed = true;
      }
    }
  }
  for (const screenId of screens.keys()) {
    if (!reachable.has(screenId)) issues.push(`${screenId}: unreachable from SCREEN-HOME`);
  }
  for (const { from, to, actionId, routeCheck = true } of EXPERIENCE_FLOW_EDGES) {
    if (!screens.has(from)) issues.push(`edge source missing: ${from}`);
    if (!screens.has(to)) issues.push(`edge target missing: ${to}`);
    const source = screens.get(from);
    const target = screens.get(to);
    const action = actions.get(actionId);
    if (source && actionId !== source.primaryActionId && !source.secondaryActionIds.includes(actionId)) {
      issues.push(`${source.screenId}: edge action ${actionId} is not declared by the screen`);
    }
    if (source && target && action?.nextRoute && routeCheck) {
      if (!locationMatchesScreenTemplate(action.nextRoute, target.routeTemplate)) {
        issues.push(
          `${source.screenId}: ${action.actionId} hands off to ${action.nextRoute}, expected ${target.routeTemplate}`,
        );
      }
    } else if (source && target && routeCheck) {
      issues.push(
        `${source.screenId}: primary action does not declare handoff to ${target.screenId}`,
      );
    }
  }
  return issues;
}
