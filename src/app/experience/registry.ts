const feedback = (loading: string, success: string, recoverableError: string) => ({
  loading,
  success,
  recoverableError,
});

type NavigationActionInput = Pick<
  ActionContract,
  | "actionId"
  | "label"
  | "object"
  | "nextRoute"
  | "analyticsEvent"
  | "accessibleName"
  | "testId"
> & {
  preconditions?: readonly string[];
  permissions?: readonly string[];
  sideEffect?: string;
  persistence?: ActionContract["persistence"];
};

const navigationAction = (input: NavigationActionInput): ActionContract => ({
  actionId: input.actionId,
  label: input.label,
  type: "NAV",
  object: input.object,
  preconditions: input.preconditions || ["current route context available"],
  permissions: input.permissions || ["workspace:read"],
  sideEffect:
    input.sideEffect ||
    `opens ${input.object} while preserving the current workspace context`,
  feedback: feedback(
    `Abrindo ${input.label.toLowerCase()}…`,
    `${input.label} aberto`,
    "O contexto atual foi preservado; tente novamente.",
  ),
  persistence: input.persistence || "none",
  nextRoute: input.nextRoute,
  analyticsEvent: input.analyticsEvent,
  accessibleName: input.accessibleName,
  testId: input.testId,
});

type LocalActionInput = Pick<
  ActionContract,
  "actionId" | "label" | "object" | "analyticsEvent" | "accessibleName" | "testId"
> & {
  type?: ActionContract["type"];
  preconditions?: readonly string[];
  permissions?: readonly string[];
  sideEffect?: string;
  persistence?: ActionContract["persistence"];
};

const localAction = (input: LocalActionInput): ActionContract => ({
  actionId: input.actionId,
  label: input.label,
  type: input.type || "SELECT",
  object: input.object,
  preconditions: input.preconditions || ["current surface is ready"],
  permissions: input.permissions || ["content:read"],
  sideEffect:
    input.sideEffect ||
    `updates ${input.object} without changing unrelated product state`,
  feedback: feedback(
    `Atualizando ${input.label.toLowerCase()}…`,
    `${input.label} atualizado`,
    "O estado anterior foi preservado; tente novamente.",
  ),
  persistence: input.persistence || "local",
  analyticsEvent: input.analyticsEvent,
  accessibleName: input.accessibleName,
  testId: input.testId,
});

