"""Fresh canonical copies of the three authored studies, never human approval.

Uses the existing isolated laboratory identity and original licensed/owned
assets. Historical projects, MP4s, requests and reviews remain unchanged.
One job is submitted at a time; collection does not execute or duplicate it.
"""
# ruff: noqa: E402
import argparse
import copy
import hashlib
import json
import runpy
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
study = runpy.run_path(str(ROOT / "scripts/validation/visual-distance-study.py"))
study["api"].__globals__["BASE"] = "http://127.0.0.1:8000/api/v1"
api = study["api"]
OLD = ROOT / "output/visual-distance-20261002"
OUT = ROOT / "output/visual-directed-native14-20261004"
OUT.mkdir(exist_ok=True)
STATE = OUT / "execution.json"
original = json.loads((OLD / "execution.json").read_text(encoding="utf-8"))
_, workspace_id = study["identity"]()
assert workspace_id == original["workspaceId"]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def save(state):
    STATE.write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")


def retain(name, value):
    target = OUT / name
    assert not target.exists(), "Preserve retained evidence: " + name
    target.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")


state = json.loads(STATE.read_text(encoding="utf-8")) if STATE.exists() else {
    "scope": "fresh_real_API_copies_of_authored_studies_not_autonomous_direction",
    "workspaceId": workspace_id, "historicalExecutionSha256": sha(OLD / "execution.json"),
    "paidApiSpendUsd": 0, "humanReview": "not_assessed", "autonomy": "not_demonstrated",
    "interventions": ["Original authored direction reused, not generated by a planner.",
        "Fresh documents/plans on the same original assets; expected revision rebound explicitly.",
        "Current native.14 execution, high/CRF10 output; no assumption of visual improvement.",
        "No new media source, paid generation, human score or blind preference invented."],
    "variants": {}, "comparisons": {}}
assert state["historicalExecutionSha256"] == sha(OLD / "execution.json")
parser = argparse.ArgumentParser()
parser.add_argument("mode", choices=["prepare", "render", "recover", "recover-stopped", "retry", "collect", "status", "compare"])
parser.add_argument("--key", choices=[v["key"] for v in original["variants"]])
parser.add_argument("--study", choices=["organization", "comparison", "interface"])
args = parser.parse_args()

if args.mode == "compare":
    assert args.study
    variants = [v for v in state["variants"].values() if v["study"] == args.study]
    assert len(variants) == 3 and all(v.get("status") == "succeeded" for v in variants)
    assert args.study not in state["comparisons"], "Preserve existing blind session"
    request = {"variants": [{"documentId": v["documentId"], "documentRevision": v["revision"],
        "assetId": v["artifact"]["assetId"], "checksum": v["artifact"]["checksumSha256"]} for v in variants]}
    comparison = api(f"/studios/v1/workspaces/{workspace_id}/visual-study-comparisons", "POST", request)
    assert comparison["status"] == "not_assessed" and not comparison["blockers"]
    state["comparisons"][args.study] = comparison
    retain(args.study + "-blind-session.json", comparison)
    save(state)
    print(json.dumps({"study": args.study, "comparisonId": comparison["id"], "status": comparison["status"]}))
    sys.exit(0)

assert args.key
historical = next(v for v in original["variants"] if v["key"] == args.key)
value = state["variants"].setdefault(args.key, {"key": args.key, "study": historical["study"],
    "variant": historical["variant"], "historicalDocumentId": historical["documentId"],
    "historicalMp4Sha256": sha(OLD / (args.key + ".mp4")), "status": "not_prepared"})
assert value["historicalMp4Sha256"] == historical["result"]["artifact"]["checksumSha256"]
assert value["historicalMp4Sha256"] == sha(OLD / (args.key + ".mp4"))


def recover_render():
    """Read the committed scoped job after an HTTP timeout; never execute it."""
    from sqlalchemy import select
    from app.database import SessionLocal
    from app.models import StudioGenerationJob
    with SessionLocal() as db:
        matches = db.scalars(select(StudioGenerationJob).where(
            StudioGenerationJob.workspace_id == workspace_id,
            StudioGenerationJob.idempotency_key == "directed-native14-render-" + value["documentId"])).all()
        assert len(matches) <= 1
        if not matches:
            return False
        job = matches[0]
        snapshot = job.request_payload["documentSnapshot"]
        request = job.request_payload["renderRequest"]
        assert job.document_id == value["documentId"] and job.provider == "remotion.contextual-v2"
        assert snapshot["documentId"] == value["documentId"] and snapshot["revision"] == value["revision"]
        assert snapshot["version"] == value["version"]
        assert job.request_payload["contextualPlanId"] == value["planId"]
        assert request["output"] == {"schemaVersion": "studio.video-render-spec.v1", "format": "mp4",
            "width": 1080, "height": 1920, "fps": 30,
            "quality": "high", "videoCodec": "h264", "audioCodec": "aac"}
        live = api("/studios/v1/jobs/" + job.id)
        assert live["id"] == job.id
        if not (OUT / (args.key + "-http-recovery.json")).exists():
            retain(args.key + "-http-recovery.json", {"jobId": job.id, "status": live["status"],
                "reason": "Missing API response; existing committed job recovered without resubmission",
                "idempotencyKey": job.idempotency_key, "renderRequest": request,
                "documentId": snapshot["documentId"], "documentRevision": snapshot["revision"]})
        value.update(jobId=job.id, status=live["status"])
        save(state)
        print(json.dumps({"key": args.key, "jobId": job.id, "status": live["status"], "recovered": True}))
        return True


if args.mode == "recover":
    assert not value.get("jobId") and value["status"] == "ready"
    assert recover_render(), "No committed job found; do not assume timeout is failure"
    sys.exit(0)

if args.mode == "recover-stopped":
    from app.providers.studios.heavy_media_lease import _active, _read, lease_path
    from app.database import SessionLocal
    from app.models import StudioGenerationJob
    from app.services.studios.jobs import execute_job_once
    assert value.get("jobId") and not value.get("artifact")
    lease = _read(lease_path())
    assert lease and lease["executionId"] == value["jobId"] and not _active(lease)
    live = api("/studios/v1/jobs/" + value["jobId"])
    assert live["status"] == "running", "Only a proven stopped owner may be reconciled"
    cancelled = api("/studios/v1/jobs/" + value["jobId"] + "/cancel", "POST",
        {"reason": "Local embedded worker process stopped; lease identity confirmed absent; no output published"})
    assert cancelled["status"] == "cancel_requested"
    with SessionLocal() as db:
        job = db.get(StudioGenerationJob, value["jobId"])
        assert job.workspace_id == workspace_id and job.document_id == value["documentId"]
        assert job.status == "cancel_requested" and job.result_payload is None
        assert not _active(_read(lease_path()))
        # Existing service exits at the cancellation branch before provider
        # lookup or execution. It finalizes only this verified orphan job.
        assert execute_job_once(db, job) == "cancelled"
        assert job.result_payload is None
    after = api("/studios/v1/jobs/" + value["jobId"])
    assert after["status"] == "cancelled" and after["result"] is None
    retain(args.key + "-stopped-worker.json", {"lease": lease, "ownerAlive": False,
        "before": live, "cancelRequested": cancelled, "after": after,
        "providerExecutedDuringReconciliation": False, "outputPublished": False})
    value["status"] = "cancelled"
    state["interventions"].append("Stopped embedded worker for " + args.key +
        " reconciled through API cancellation and existing cancellation-only service branch; retry explicit.")
    save(state)
    print(json.dumps({"key": args.key, "jobId": value["jobId"], "status": "cancelled"}))
    sys.exit(0)

if args.mode == "retry":
    assert value.get("jobId") and not value.get("artifact")
    live = api("/studios/v1/jobs/" + value["jobId"])
    assert (OUT / (args.key + "-stopped-worker.json")).exists()
    assert live["status"] == "cancelled" or (
        live["status"] == "failed" and live["errorMessage"] == "video_render_provider_unavailable"
        and (OUT / (args.key + "-provider-registration-failure.json")).exists())
    try:
        retried = api("/studios/v1/jobs/" + value["jobId"] + "/retry", "POST")
    except TimeoutError:
        retried = api("/studios/v1/jobs/" + value["jobId"])
    assert retried["id"] == value["jobId"]
    value["status"] = retried["status"]
    save(state)
    print(json.dumps({"key": args.key, "jobId": value["jobId"], "status": retried["status"], "retry": True}))
    sys.exit(0)

if args.mode == "prepare":
    if not value.get("documentId"):
        source = api("/studios/v1/documents/" + historical["documentId"])
        assert source["revision"] == historical["revision"] and source["workspaceId"] == workspace_id
        plan = api("/studios/v1/documents/" + historical["documentId"] + "/editing-plans/latest")
        assert plan["id"] == historical["planId"] and plan["status"] == "applied"
        for name, data in [(args.key + "-source-document.json", source), (args.key + "-source-plan.json", plan)]:
            if not (OUT / name).exists():
                retain(name, data)
        assert all(asset["rightsStatus"] == "verified" and asset["checksum"] for asset in source["assets"])
        if not value.get("postId"):
            post = api("/posts", "POST", {"workspaceId": workspace_id, "title": "Estudo native14 / " + args.key,
                "platform": "instagram", "format": "reels", "status": "draft", "origin": "manual",
                "objective": source["brief"]["objective"], "copy": "Estudo dirigido; revisão humana pendente.", "author": "Laboratório res"})
            value["postId"] = post["id"]
            save(state)
        document = api("/studios/v1/documents", "POST", {"workspaceId": workspace_id, "postId": value["postId"],
            "title": "Estudo native14 / " + args.key, "contentType": "video", "brandRevision": 1,
            "brief": copy.deepcopy(source["brief"]), "assets": copy.deepcopy(source["assets"]),
            "composition": {"pages": [{"id": "page", "width": 1080, "height": 1920, "safeArea": 90,
                "background": "#101416", "durationMs": 15000, "layers": []}]}})
        value.update(documentId=document["documentId"], revision=document["revision"],
                     sourceChecksums={a["id"]: a["checksum"] for a in document["assets"]},
                     url=f"http://127.0.0.1:3000/content/{value['postId']}/edit?mode=video")
        save(state)
    if not value.get("planId"):
        source_plan = json.loads((OUT / (args.key + "-source-plan.json")).read_text(encoding="utf-8"))
        document = api("/studios/v1/documents/" + value["documentId"])
        direction = copy.deepcopy(source_plan["direction"])
        direction["expectedDocumentRevision"] = document["revision"]
        assert {k: v for k, v in direction.items() if k != "expectedDocumentRevision"} == {
            k: v for k, v in source_plan["direction"].items() if k != "expectedDocumentRevision"}
        if not (OUT / (args.key + "-request.json")).exists():
            retain(args.key + "-request.json", direction)
        plan = api("/studios/v1/documents/" + value["documentId"] + "/editing-plans", "POST", direction,
            "directed-native14-" + args.key + "-" + value["documentId"])
        retain(args.key + "-plan.json", plan)
        assert plan["status"] == "ready", plan["blockers"]
        value["planId"] = plan["id"]
        save(state)
    if value["status"] == "not_prepared":
        plan = api("/studios/v1/documents/" + value["documentId"] + "/editing-plans/latest")
        assert plan["id"] == value["planId"] and plan["status"] in {"ready", "applied"}
        if plan["status"] == "ready":
            document = api("/studios/v1/documents/" + value["documentId"] + f"/editing-plans/{plan['id']}/apply",
                "POST", {"expectedPlanRevision": plan["revision"]})
        else:
            document = api("/studios/v1/documents/" + value["documentId"])
            assert document["composition"]["narrative"]["contextualPlanId"] == plan["id"]
        value.update(revision=document["revision"], version=document["version"], status="ready")
        retain(args.key + "-document.json", document)
        save(state)
    print(json.dumps({"key": args.key, "status": value["status"], "documentId": value["documentId"]}))
elif args.mode == "render":
    assert value["status"] == "ready" and not value.get("jobId")
    if recover_render():
        sys.exit(0)
    # Keep one current study render at a time, including when a prior caller
    # exited while the worker was still running.
    for other in state["variants"].values():
        if other.get("jobId") and other.get("status") != "succeeded":
            live = api("/studios/v1/jobs/" + other["jobId"])
            assert live["status"] not in {"queued", "running", "retrying", "cancel_requested"}, live["id"]
    from app.providers.studios.heavy_media_lease import _active, _read, lease_path
    assert not _active(_read(lease_path())), "A live media operation owns shared capacity"
    try:
        job = api("/studios/v1/video-renders", "POST", {"workspaceId": workspace_id,
        "documentId": value["documentId"], "expectedDocumentRevision": value["revision"],
        "expectedDocumentVersion": value["version"], "contextualPlanId": value["planId"],
        "provider": "remotion.contextual-v2", "output": {"width": 1080, "height": 1920, "fps": 30,
            "quality": "high", "videoCodec": "h264", "audioCodec": "aac"}},
            "directed-native14-render-" + value["documentId"])
    except TimeoutError:
        if not recover_render():
            raise
        sys.exit(0)
    value.update(jobId=job["id"], status=job["status"])
    save(state)
    print(json.dumps({"key": args.key, "jobId": job["id"], "status": job["status"]}))
else:
    assert value.get("jobId"), "Submit one real API job first"
    live = api("/studios/v1/jobs/" + value["jobId"])
    print(json.dumps({"key": args.key, "jobId": live["id"], "status": live["status"], "error": live.get("errorMessage")}), flush=True)
    if args.mode == "status" or live["status"] in {"queued", "running", "retrying", "cancel_requested"}:
        sys.exit(0)
    assert live["status"] == "succeeded", live.get("errorMessage")
    assert not value.get("artifact"), "Keep collected artifact intact"
    from app.database import SessionLocal
    from app.models import LibraryAsset, StudioGenerationJob
    from app.services.object_storage import get_object_storage
    with SessionLocal() as db:
        job = db.get(StudioGenerationJob, value["jobId"])
        assert job.status == "succeeded" and job.workspace_id == workspace_id
        snapshot, result = job.request_payload["documentSnapshot"], job.result_payload
        assert snapshot["documentId"] == value["documentId"] and snapshot["revision"] == value["revision"]
        assert result["providerVersion"] == "4.0.527-native.14"
        assert result["qualityEvaluation"]["status"] == "passed" and result["framesRendered"] == 450
        asset = db.get(LibraryAsset, result["artifact"]["assetId"])
        target = OUT / (args.key + ".mp4")
        assert not target.exists()
        with get_object_storage(asset.storage_backend).materialize(asset.storage_key) as source:
            shutil.copy2(source, target)
        assert sha(target) == result["artifact"]["checksumSha256"]
        assert {b["assetId"]: b["checksumSha256"] for b in asset.object_metadata["sourceAssetBindings"]} == {
            b["assetId"]: b["checksumSha256"] for b in historical["metadata"]["sourceAssetBindings"]}
        retain(args.key + "-render.json", {"scope": "real_API_job_current_kernel_original_authored_direction",
            "snapshot": snapshot, "renderResult": result, "renderMetadata": asset.object_metadata,
            "outputRequest": job.request_payload["renderRequest"]["output"],
            "historicalArtifactSha256": value["historicalMp4Sha256"], "humanReview": "not_assessed",
            "interventions": state["interventions"]})
        value.update(status="succeeded", artifact=result["artifact"], renderDurationMs=result["renderDurationMs"])
        save(state)
